// V66ProofDraft binds the audited candidate contribution to a later actual
// placement observation. The draft is not a LegacyDayProof and carries no
// publication capability. Its exact SHA must come from the reviewed artifact.
type V66ProofDraft struct {
	Version             string  `json:"version"`
	Cutover             *int64  `json:"cutover_ms"`
	Placement           *string `json:"placement_report_sha256"`
	PlacementObserved   bool    `json:"placement_observed"`
	PublicationApproved bool    `json:"publication_approved"`
	Sealed              bool    `json:"sealed"`
	Days                []struct {
		Day                  string        `json:"day"`
		From                 int64         `json:"from_ms"`
		To                   int64         `json:"to_ms_exclusive"`
		Status               string        `json:"status"`
		CandidateSHA         string        `json:"candidate_sha256"`
		CandidateBytes       int64         `json:"candidate_bytes"`
		CanonicalRowsSHA256  string        `json:"canonical_rows_sha256"`
		Sources              []SourceProof `json:"sources"`
		UniqueSpot           int64         `json:"unique_spot"`
		UniqueFutures1m      int64         `json:"unique_futures_1m"`
		DuplicateOccurrences int64         `json:"duplicate_occurrences"`
		Quarantined          int64         `json:"quarantined"`
		Conflicts            int64         `json:"conflicts"`
		UnknownAvailability  int64         `json:"unknown_availability"`
		Cutover              *int64        `json:"cutover_ms"`
		Placement            *string       `json:"placement_report_sha256"`
		PublicationApproved  bool          `json:"publication_approved"`
	} `json:"days"`
}

type V66ReviewedProofs struct {
	Version               string           `json:"version"`
	DraftSHA256           string           `json:"draft_sha256"`
	PlacementReportSHA256 string           `json:"placement_report_sha256"`
	PublicationApproved   bool             `json:"publication_approved"`
	Proofs                []LegacyDayProof `json:"proofs"`
	HeldDays              []string         `json:"held_days"`
}

// BindV66Proofs is offline planning only. expectedDraft and expectedPlacement
// are independently supplied reviewed digests, not generated by this function.
// A caller must separately establish the placement report's truth, freshness,
// stopped-writer state and actual cutover. No production publication is allowed.
func BindV66Proofs(draft []byte, expectedDraft string, r PlacementReport, expectedPlacement string) (V66ReviewedProofs, error) {
	var z V66ReviewedProofs
	if len(draft) == 0 || len(draft) > 2<<20 || !validHash(expectedDraft) || hash(draft) != expectedDraft {
		return z, errors.New("V66 draft digest differs")
	}
	_, placement, e := CanonicalPlacementReport(r)
	if e != nil {
		return z, e
	}
	if !validHash(expectedPlacement) || placement != expectedPlacement {
		return z, errors.New("placement digest differs")
	}
	var d V66ProofDraft
	dec := json.NewDecoder(bytes.NewReader(draft))
	if e = dec.Decode(&d); e != nil {
		return z, e
	}
	var extra any
	if e = dec.Decode(&extra); e != io.EOF {
		return z, errors.New("trailing draft JSON")
	}
	if d.Version != "v66-source-review-draft-v1" || d.Cutover != nil || d.Placement != nil || d.PlacementObserved || d.PublicationApproved || d.Sealed || len(d.Days) != 57 || len(r.Days) != 57 {
		return z, errors.New("unreviewed draft required and placement must cover all 57 dates")
	}
	out := V66ReviewedProofs{Version: "v66-bound-review-v1", DraftSHA256: expectedDraft, PlacementReportSHA256: placement}
	loc := time.FixedZone("UTC+8", 8*3600)
	first := time.Date(2026, 9, 20, 0, 0, 0, 0, loc)
	var eligible, held int64
	for i, x := range d.Days {
		a := first.AddDate(0, 0, i)
		day := a.Format("2006-01-02")
		end := a.AddDate(0, 0, 1).UnixMilli()
		if x.Day != day || r.Days[i].Day != day || x.From != a.UnixMilli() || x.To != end || x.Cutover != nil || x.Placement != nil || x.PublicationApproved || !validHash(x.CandidateSHA) || x.CandidateBytes <= 0 || !validHash(x.CanonicalRowsSHA256) || len(x.Sources) != 1 {
			return z, fmt.Errorf("invalid candidate day %s", day)
		}
		s := x.Sources[0]
		n := x.UniqueSpot + x.UniqueFutures1m
		if x.UniqueSpot < 0 || x.UniqueSpot > 17280 || x.UniqueFutures1m < 0 || x.UniqueFutures1m > 4320 || n <= 0 || x.UnknownAvailability != n || x.DuplicateOccurrences != 0 || x.Quarantined != 0 || x.Conflicts != 0 || s.Adapter != "v66-browser-jsonl-v1" || s.MappedOccurrences != n || !validHash(s.CompressedSHA256) || !validHash(s.UncompressedSHA256) || !validHash(s.MappingSHA256) || !validHash(s.AuditSHA256) {
			return z, fmt.Errorf("invalid evidence counts %s", day)
		}
		if i >= 55 {
			if x.Status != "hold_overlap_review" {
				return z, errors.New("held day must stay isolated")
			}
			out.HeldDays = append(out.HeldDays, day)
			held += n
			continue
		}
		if x.Status != "source_review_candidate" {
			return z, errors.New("unexpected draft disposition")
		}
		p := LegacyDayProof{Version: "legacy-day-proof-v1", Day: day, CutoverMS: r.CutoverMS, Sources: x.Sources, CanonicalRowsSHA256: x.CanonicalRowsSHA256, PlacementReportSHA256: placement, UniqueSpot: x.UniqueSpot, UniqueFutures1m: x.UniqueFutures1m, UnknownAvailability: x.UnknownAvailability}
		if e = MatchProofPlacement(p, r); e != nil {
			return z, fmt.Errorf("%s: %w", day, e)
		}
		out.Proofs = append(out.Proofs, p)
		eligible += n
	}
	if eligible != 1042893 || held != 22500 || len(out.Proofs) != 55 || len(out.HeldDays) != 2 {
		return z, errors.New("review totals differ")
	}
	return out, nil
}
